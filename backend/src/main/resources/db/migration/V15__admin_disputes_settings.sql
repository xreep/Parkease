CREATE TABLE admin_actions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id    BIGINT        NOT NULL REFERENCES users (id),
    action      VARCHAR(60)   NOT NULL,
    target_type VARCHAR(40)   NOT NULL,
    target_id   BIGINT,
    details     VARCHAR(1000),
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_admin_actions_created ON admin_actions (created_at DESC, id DESC);

CREATE TABLE disputes (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id         BIGINT         NOT NULL REFERENCES bookings (id) ON DELETE CASCADE,
    raised_by          BIGINT         NOT NULL REFERENCES users (id),
    category           VARCHAR(20)    NOT NULL
        CHECK (category IN ('NO_ACCESS','SLOT_OCCUPIED','OVERSTAY','DAMAGE','PAYMENT','OTHER')),
    description        VARCHAR(2000)  NOT NULL,
    status             VARCHAR(20)    NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','UNDER_REVIEW','RESOLVED')),
    owner_response     VARCHAR(1000),
    owner_responded_at TIMESTAMPTZ,
    admin_notes        VARCHAR(1000),
    resolution         VARCHAR(20)    CHECK (resolution IN ('REFUND_FULL','REFUND_PARTIAL','NO_REFUND','WARNING')),
    resolution_amount  NUMERIC(10, 2) CHECK (resolution_amount >= 0),
    resolved_at        TIMESTAMPTZ,
    created_at         TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE INDEX idx_disputes_booking ON disputes (booking_id);
CREATE INDEX idx_disputes_status_created ON disputes (status, created_at);
-- One unresolved dispute per booking, enforced by the database so concurrent requests cannot both open one.
CREATE UNIQUE INDEX uq_disputes_one_open_per_booking ON disputes (booking_id) WHERE status <> 'RESOLVED';

