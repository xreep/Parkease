-- Key/value settings. No foreign key on updated_by on purpose: settings are reference data that must outlive users.
CREATE TABLE platform_settings (
    key        VARCHAR(60)  PRIMARY KEY,
    value      VARCHAR(100) NOT NULL,
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by BIGINT
);

